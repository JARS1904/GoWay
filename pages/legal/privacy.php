      <h2>1. Nuestra filosofía sobre los datos</h2>
      <p>En GoWay creemos firmemente que la tecnología debe empoderar a la sociedad, facilitando la logística y la movilidad sin comprometer la privacidad individual. Diseñamos nuestra arquitectura de software basándonos en el principio de recolección mínima: solo almacenamos lo estrictamente necesario para que tu experiencia en la plataforma sea impecable y segura.</p>
