    <div class="legal-section" id="s2">
      <h2>2. Información que recopilamos</h2>
      <p>Para asegurar el correcto funcionamiento de la logística de transporte, GoWay procesa distintos conjuntos de datos dependiendo del rol del usuario dentro de la plataforma:</p>
      
      <h3>2.1 Usuarios y pasajeros</h3>
      <ul>
        <li><strong>Datos de Cuenta:</strong> Nombre completo, dirección de correo electrónico y credenciales encriptadas para la autenticación.</li>
        <li><strong>Preferencias de Interfaz:</strong> Ajustes visuales y de configuración para brindar una experiencia personalizada.</li>
      </ul>

      <h3>2.2 Empresas de transporte</h3>
      <ul>
        <li><strong>Información Corporativa:</strong> Nombre de la organización, razón social y datos de contacto del administrador.</li>
        <li><strong>Datos Operativos:</strong> Rutas establecidas, flotilla de vehículos registrados y bases de operación asignadas.</li>
      </ul>

      <h3>2.3 Checadores de ruta</h3>
      <ul>
        <li><strong>Información de Personal:</strong> Nombre, número de teléfono y el identificador de la ruta a la que han sido asignados por su empresa de transporte.</li>
        <li><strong>Registros de Actividad:</strong> Horarios de llegada y salida (check-ins) de las unidades en los puntos de control.</li>
      </ul>
    </div>

    <div class="legal-section" id="s3">
      <h2>3. Uso del mapa y ubicaciones</h2>
      <p>Una de las prioridades de GoWay es brindar información precisa sobre las paradas y bases del transporte público utilizando tecnología de mapas de CARTO. Es fundamental aclarar nuestro enfoque sobre el manejo de ubicaciones:</p>
      <div class="legal-highlight">
        <p><strong>Cero Rastreo en Tiempo Real:</strong> GoWay <strong>no emplea</strong> geolocalización en tiempo real para rastrear unidades de transporte, usuarios, pasajeros o checadores. Nuestro mapa es una herramienta estática y de referencia visual diseñada exclusivamente para ilustrar dónde se encuentran ubicadas las paradas y las bases oficiales.</p>
      </div>
      <p>No almacenamos ni transmitimos historiales de tus trayectos físicos. Tu ubicación personal y la de tu dispositivo permanecen privadas y bajo tu total control en todo momento.</p>
    </div>

    <div class="legal-section" id="s4">
      <h2>4. Cómo utilizamos tu información</h2>
      <p>Toda la información recabada tiene propósitos puramente operativos y de mejora continua de los servicios de GoWay. Utilizamos los datos para:</p>
      <ul>
        <li><strong>Autenticación y Seguridad:</strong> Validar el acceso a los diferentes paneles de control (Administrador, Checador, Usuario).</li>
        <li><strong>Gestión de Logística:</strong> Permitir a las empresas de transporte organizar a sus checadores, vehículos y reportes de incidentes.</li>
        <li><strong>Comunicación:</strong> Enviar notificaciones críticas del sistema, alertas de cambios en las rutas o avisos sobre mantenimientos programados.</li>
      </ul>
      <p>GoWay <strong>nunca vende, cede ni alquila</strong> la información personal de sus usuarios a agencias de marketing o corporaciones de terceros.</p>
    </div>

    <div class="legal-section" id="s5">
      <h2>5. Almacenamiento y protección técnica</h2>
      <p>Implementamos estándares de seguridad rigurosos para salvaguardar tu información frente a accesos no autorizados, alteraciones o destrucción. Entre nuestras medidas se incluyen:</p>
      <ul>
        <li>Encriptación avanzada de contraseñas mediante algoritmos de hash seguros (bcrypt).</li>
        <li>Comunicaciones cifradas a través de protocolos SSL/TLS en todas las interacciones con el servidor.</li>
        <li>Aislamiento de bases de datos y acceso restringido exclusivo al personal técnico autorizado.</li>
      </ul>
    </div>

    <div class="legal-section" id="s6">
      <h2>6. Tus derechos sobre tu información</h2>
      <p>Como titular de tus datos, posees el control absoluto sobre ellos. Tienes derecho a:</p>
      <ul>
        <li><strong>Acceder y Rectificar:</strong> Modificar tu nombre, correo o contraseña directamente desde los ajustes de tu cuenta.</li>
        <li><strong>Supresión de Datos:</strong> Solicitar la eliminación permanente de tu cuenta y toda la información asociada a ella.</li>
      </ul>
      <p>Las empresas pueden gestionar y eliminar los registros de sus vehículos y checadores en cualquier momento, lo cual se reflejará inmediatamente en el sistema central.</p>
    </div>

